#!/usr/bin/env bash
# Create Kubernetes Secrets for SeaweedFS and the inference service.
#
# Credentials are either taken from the environment (AWS_ACCESS_KEY_ID /
# AWS_SECRET_ACCESS_KEY) or generated with openssl.  Generated values are
# written to .env.local (mode 0600, git-ignored) so that host-side scripts
# such as scripts/init_storage.py can use the same credentials.
#
# This script never writes credentials into the repository.
set -euo pipefail

cd "$(dirname "$0")/.."

if ! command -v kubectl >/dev/null 2>&1; then
  echo "kubectl is required" >&2
  exit 1
fi

if [[ -f .env.local ]]; then
  # shellcheck disable=SC1091
  source .env.local
fi

AWS_ACCESS_KEY_ID="${AWS_ACCESS_KEY_ID:-admin}"
AWS_SECRET_ACCESS_KEY="${AWS_SECRET_ACCESS_KEY:-$(openssl rand -hex 24)}"
S3_ENDPOINT="${S3_ENDPOINT:-http://localhost:8333}"

umask 077
cat > .env.local <<EOF
# Generated by scripts/create_secrets.sh. Do not commit this file.
AWS_ACCESS_KEY_ID=${AWS_ACCESS_KEY_ID}
AWS_SECRET_ACCESS_KEY=${AWS_SECRET_ACCESS_KEY}
S3_ENDPOINT=${S3_ENDPOINT}
EOF
umask 022

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

python3 - "$tmp/s3.json" <<'PY'
import json, os, sys
identity = {
    "name": os.environ.get("SEAWEEDFS_S3_IDENTITY", "admin"),
    "credentials": [{
        "accessKey": os.environ["AWS_ACCESS_KEY_ID"],
        "secretKey": os.environ["AWS_SECRET_ACCESS_KEY"],
    }],
    "actions": ["Admin", "Read", "Write", "List", "Tagging"],
}
with open(sys.argv[1], "w", encoding="utf-8") as fh:
    json.dump({"identities": [identity]}, fh, indent=2)
    fh.write("\n")
PY

kubectl -n data create secret generic seaweedfs-s3-config \
  --from-file=s3.json="$tmp/s3.json" \
  --dry-run=client -o yaml | kubectl apply -f - >/dev/null

for ns in data app pipeline; do
  kubectl -n "$ns" create secret generic model-store-credentials \
    --from-literal=AWS_ACCESS_KEY_ID="$AWS_ACCESS_KEY_ID" \
    --from-literal=AWS_SECRET_ACCESS_KEY="$AWS_SECRET_ACCESS_KEY" \
    --dry-run=client -o yaml | kubectl apply -f - >/dev/null
done

kubectl -n pipeline create configmap teacher-prompt \
  --from-file=teacher_prompt.txt=prompts/teacher_prompt.txt \
  --dry-run=client -o yaml | kubectl apply -f - >/dev/null

echo "Secrets applied: data/seaweedfs-s3-config, {data,app,pipeline}/model-store-credentials"
echo "Credentials stored locally in .env.local (git-ignored)."
