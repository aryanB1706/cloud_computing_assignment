#!/usr/bin/env python3
"""Create the datasets/models buckets and upload kit data to SeaweedFS (Task 1).

Run against a port-forward or the k3d port mapping:

    kubectl -n data port-forward svc/seaweedfs-s3 8333:8333 &
    python scripts/init_storage.py --endpoint http://localhost:8333

Credentials are read from AWS_ACCESS_KEY_ID / AWS_SECRET_ACCESS_KEY, normally
sourced from .env.local generated by scripts/create_secrets.sh.
"""

from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "worker"))

from storage import DATASETS_BUCKET, MODELS_BUCKET, S3Store  # noqa: E402


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--endpoint", default=os.environ.get("S3_ENDPOINT", "http://localhost:8333")
    )
    parser.add_argument("--data-dir", default="data")
    parser.add_argument("--commands-file", default="commands_pool.jsonl")
    parser.add_argument("--skip-commands", action="store_true")
    parser.add_argument(
        "--models-dir",
        default=None,
        help="optional local model directory to upload (e.g. models/v1)",
    )
    parser.add_argument("--version", default="v1", help="models/<version>/ prefix")
    args = parser.parse_args()

    store = S3Store(endpoint=args.endpoint)
    for bucket in (DATASETS_BUCKET, MODELS_BUCKET):
        store.ensure_bucket(bucket)
        print(f"bucket ready: {bucket}")

    if not args.skip_commands:
        source = Path(args.data_dir) / args.commands_file
        if not source.is_file():
            print(f"missing {source}; run from the repository root", file=sys.stderr)
            return 1
        store.put_file(DATASETS_BUCKET, args.commands_file, source)
        size = source.stat().st_size
        print(f"uploaded {source} -> s3://{DATASETS_BUCKET}/{args.commands_file} ({size} bytes)")

    if args.models_dir:
        base = Path(args.models_dir)
        if not base.is_dir():
            print(f"models dir {base} does not exist", file=sys.stderr)
            return 1
        prefix = args.version.strip("/")
        for path in sorted(p for p in base.rglob("*") if p.is_file()):
            key = f"{prefix}/{path.relative_to(base).as_posix()}"
            store.put_file(MODELS_BUCKET, key, path)
            print(f"uploaded {path} -> s3://{MODELS_BUCKET}/{key}")

    print("objects in datasets:", ", ".join(store.list(DATASETS_BUCKET)) or "(empty)")
    print("objects in models:", ", ".join(store.list(MODELS_BUCKET)) or "(empty)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
